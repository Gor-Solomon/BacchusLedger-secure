using System.Reflection;
using BacchusLedger.Application.Options;
using BacchusLedger.Application.Repositories;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Storage;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace BacchusLedger.Infrastructure.Persistence;

/// Applies the EF Core migrations and seeds an empty database.
public sealed class DatabaseInitializer(
    BacchusLedgerDbContext db, IUnitOfWork unitOfWork, IWineryRepository wineries, IReadingRepository readings, DatabaseSeeder seeder,
    SqliteWriteGate gate, IOptions<StorageOptions> storage, ILogger<DatabaseInitializer> logger) : IDatabaseInitializer
{
    public async Task InitializeAsync(bool reset)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(storage.Value.DbPath));
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        await MigrateAsync(reset);
        if ((await wineries.ListAsync()).Count == 0) await unitOfWork.WriteAsync(async () => { await seeder.SeedAsync(); return 0; });
        // Databases created before readings existed: add the dataset readings once.
        else if (await readings.CountFromDatasetAsync() == 0) await unitOfWork.WriteAsync(async () => { await seeder.SeedReadingsFromLabAsync(); return 0; });
    }

    public Task ResetAndSeedAsync() => InitializeAsync(reset: true);

    /// reset: migrate down to nothing (drops every table) and up again, so the database file itself stays.
    async Task MigrateAsync(bool reset)
    {
        await gate.WaitAsync();
        try
        {
            await BaselineLegacyDatabaseAsync();
            var migrator = db.GetService<IMigrator>();
            if (reset) await migrator.MigrateAsync(Migration.InitialDatabase);
            await db.Database.MigrateAsync();
        }
        finally { gate.Release(); }
    }

    /// A database made by the app before EF Core has all the tables of InitialSchema but no migrations history:
    /// record InitialSchema as applied instead of creating the tables again, so all data stays.
    async Task BaselineLegacyDatabaseAsync()
    {
        if (!await db.GetService<IRelationalDatabaseCreator>().HasTablesAsync() || (await db.Database.GetAppliedMigrationsAsync()).Any()) return;
        var initial = db.Database.GetMigrations().First();
        var version = typeof(DbContext).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()!.InformationalVersion.Split('+')[0];
        var history = db.GetService<IHistoryRepository>();
        // EF Core's own history-table scripts (generated by EF, not hand-written SQL).
        await db.Database.ExecuteSqlRawAsync(history.GetCreateIfNotExistsScript());
        await db.Database.ExecuteSqlRawAsync(history.GetInsertScript(new HistoryRow(initial, version)));
        logger.LogInformation("database: existing tables recorded as migration {Migration} (baseline, data kept)", initial);
    }
}
